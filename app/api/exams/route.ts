function shuffle<T>(items: T[]): T[] {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

async function readSessions(): Promise<ExamSession[]> {
  try {
    return JSON.parse(await fs.readFile(SESSIONS_FILE, "utf8")) as ExamSession[];
  } catch {
    return [];
  }
}

async function writeSessions(sessions: ExamSession[]) {
  await fs.mkdir(path.dirname(SESSIONS_FILE), { recursive: true });
  await fs.writeFile(SESSIONS_FILE, JSON.stringify(sessions, null, 2), "utf8");
}

function getUserId(request: Request) {
  const cookie = request.headers.get("cookie") || "";
  const token = cookie
    .split(";")
    .map((item) => item.trim())
    .find((item) => item.startsWith("miftah_session="))
    ?.split("=")
    .slice(1)
    .join("=");
  return userIdFromToken(token);
}

export async function POST(request: Request) {
  try {
    const userId = getUserId(request);
    if (!userId) return NextResponse.json({ error: "سجّل الدخول أولًا لبدء الامتحان وحفظ XP." }, { status: 401 });

    const body = await request.json();
    const action = String(body?.action || "");
    const sessions = await readSessions();
    const now = Date.now();

    if (action === "start") {
      const subject = String(body?.subject || "") as Subject;
      const difficulty = String(body?.difficulty || "") as Difficulty;
      if (!Object.prototype.hasOwnProperty.call(banks, subject)) {
        return NextResponse.json({ error: "المادة المختارة غير صحيحة." }, { status: 400 });
      }
      if (!["easy", "medium", "hard"].includes(difficulty)) {
        return NextResponse.json({ error: "اختار مستوى صعوبة صحيح." }, { status: 400 });
      }

      // Invalidate earlier unfinished attempts so one user cannot farm XP from the same exam session.
      for (const old of sessions) {
        if (old.userId === userId && !old.completedAt) old.completedAt = now;
      }

      const count = difficulty === "easy" ? 15 : difficulty === "medium" ? 20 : 25;
      const selected = shuffle(banks[subject]).slice(0, count);
      if (selected.length < count) {
        return NextResponse.json({ error: "عدد الأسئلة المتاحة غير كافٍ لهذا المستوى." }, { status: 500 });
      }

      const questions: ExamQuestion[] = selected.map((item) => {
        const choices = shuffle([item.correct, ...item.wrong]);
        return {
          id: randomUUID(),
          q: item.q,
          answers: choices,
          correctIndex: choices.indexOf(item.correct),
        };
      });
      const session: ExamSession = {
        id: randomUUID(),
        userId,
        subject,
        difficulty,
        questions,
        createdAt: now,
      };
      sessions.push(session);
      await writeSessions(sessions);

      return NextResponse.json({
        ok: true,
        examId: session.id,
        questions: questions.map(({ id, q, answers }) => ({ id, q, answers })),
      });
    }

    if (action !== "finish") return NextResponse.json({ error: "طلب غير صحيح." }, { status: 400 });

    const examId = String(body?.examId || "");
    const submitted = body?.answers;
    const session = sessions.find((item) => item.id === examId && item.userId === userId);
    if (!session) return NextResponse.json({ error: "الامتحان غير موجود. ابدأ امتحانًا جديدًا." }, { status: 404 });
    if (session.completedAt) return NextResponse.json({ error: "تم تسليم الامتحان بالفعل. ابدأ امتحانًا جديدًا." }, { status: 409 });
    if (Date.now() - session.createdAt > 3 * 60 * 60 * 1000) {
      session.completedAt = Date.now();
      await writeSessions(sessions);
      return NextResponse.json({ error: "انتهت صلاحية الامتحان. ابدأ محاولة جديدة." }, { status: 400 });
    }
    if (!Array.isArray(submitted) || submitted.length !== session.questions.length || submitted.some((answer: unknown) => !Number.isInteger(answer))) {
      return NextResponse.json({ error: "الإجابات المرسلة غير مكتملة." }, { status: 400 });
    }

    const score = session.questions.reduce((total, question, index) => {
      return total + (submitted[index] === question.correctIndex ? 1 : 0);
    }, 0);
    const total = session.questions.length;
    const wrong = total - score;
    const passed = wrong <= 1;
    const xpAwarded = passed ? 5 + Math.floor((score / total) * 15) : 0;

    const users = await readUsers();
    const user = users.find((item) => item.id === userId);
    if (!user) return NextResponse.json({ error: "الحساب غير موجود." }, { status: 404 });

    if (xpAwarded > 0) {
      user.xp = Math.max(0, Number(user.xp) || 0) + xpAwarded;
      await writeUsers(users);
    }
    session.completedAt = Date.now();
    session.score = score;
    session.xpAwarded = xpAwarded;
    await writeSessions(sessions);

    return NextResponse.json({ ok: true, score, total, passed, xpAwarded, xp: Number(user.xp) || 0 });
  } catch (error) {
    console.error("EXAM API ERROR:", error);
    return NextResponse.json({ error: "حدث خطأ أثناء تجهيز الامتحان أو تصحيحه." }, { status: 500 });
  }
}
